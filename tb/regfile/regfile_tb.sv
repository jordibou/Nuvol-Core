module regfile_tb;
    
    import uvm_pkg::*;
    `include "uvm_macros.svh"
    import regfile_pkg::*;

// -----------------------------------------------------------------------------------
// Clock generation
// -----------------------------------------------------------------------------------
    logic clk = 0;
    always #5 clk = ~clk;

// -----------------------------------------------------------------------------------
// Interface 
// -----------------------------------------------------------------------------------
    regfile_if vif (
        .clk    (clk)
    );

// -----------------------------------------------------------------------------------
// DUT instance
// -----------------------------------------------------------------------------------
    nuvol_regfile dut (
        .clk_i          (clk            ),
        .raddr_a_i      (vif.raddr_a    ),
        .raddr_b_i      (vif.raddr_b    ),
        .waddr_i        (vif.waddr      ),
        .wdata_i        (vif.wdata      ),
        .wen_i          (vif.wen        ),
        .rdata_a_o      (vif.rdata_a    ),
        .rdata_b_o      (vif.rdata_b    )
    );

// -----------------------------------------------------------------------------------
// Run the test
// -----------------------------------------------------------------------------------
    initial begin
        uvm_config_db #(virtual regfile_if)::set(null, "*", "vif", vif);
        run_test();
    end

// -----------------------------------------------------------------------------------
// Binding SVA module
// -----------------------------------------------------------------------------------
    bind nuvol_regfile regfile_sva u_sva (.*);

endmodule